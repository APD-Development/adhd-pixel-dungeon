#!/usr/bin/env python3
"""Lists the Cleric grudge line packs as a readable review document (docs/APD-VENDETTA-LINES.md).

Run from the repository root:  python3 -I tools/humor_review.py
Also prints the numbers a changelog footer may quote (per pool), computed from the packs and the committed id list of the previous release:
  added = ids in the packs that are not in core/src/test/resources/apd/cleric_complaint_ids.txt
Never type those numbers by hand.
"""
import glob, os, re, sys

ROOT = os.path.join('core', 'src', 'main', 'assets', 'apd', 'humor')
IDS = os.path.join('core', 'src', 'test', 'resources', 'apd', 'cleric_complaint_ids.txt')
OUT = os.path.join('docs', 'APD-VENDETTA-LINES.md')
BATCH_DIR = os.path.join('docs', 'cleric-review')
BATCH = 50


def read_packs():
    packs = []
    names = [n.strip() for n in open(os.path.join(ROOT, 'packs.txt'), encoding='utf-8') if n.strip()]
    for name in names:
        rows = []
        for raw in open(os.path.join(ROOT, name), encoding='utf-8'):
            line = raw.rstrip('\n')
            if not line.strip() or line.startswith('#'):
                continue
            f = [x.strip() for x in line.split('|')]
            rows.append(f)
        packs.append((name, rows))
    return packs


def write_batches(packs):
    """Review batches of 50, in pack order, one readable page each (id, when, Clean, Adult)."""
    rows = [f for _, rs in packs for f in rs]
    os.makedirs(BATCH_DIR, exist_ok=True)
    for old in os.listdir(BATCH_DIR):
        if old.startswith('batch-'):
            os.remove(os.path.join(BATCH_DIR, old))
    total = (len(rows) + BATCH - 1) // BATCH
    for b in range(total):
        chunk = rows[b * BATCH:(b + 1) * BATCH]
        out = [f'# Cleric lines for review: batch {b + 1} of {total}', '',
               f'Lines {b * BATCH + 1} to {b * BATCH + len(chunk)} of {len(rows)}. Reply with the ids to keep, cut or rewrite.', '']
        for f in chunk:
            when = 'any time' if f[3] == '-' else 'only when ' + f[3]
            kind = 'Appreciation' if f[0].startswith('app.') else ('counter screen' if f[1] == 'meta' else 'Hatred')
            extra = []
            if 'setup' in f[2]: extra.append('first part of a story')
            for x in f[2].split(','):
                x = x.strip()
                if x.startswith('after='): extra.append('follows ' + x[6:])
                if x == 'nextsession': extra.append('in a later session')
                if x == 'joke': extra.append('invented-number joke')
            note = (' [' + '; '.join(extra) + ']') if extra else ''
            out += [f'### {f[0]}  ({kind}, {f[1]}, {when}){note}', f'- Clean: {f[5]}', f'- Adult: {f[6] if f[6] else "(same as Clean)"}', '']
        open(os.path.join(BATCH_DIR, f'batch-{b + 1:02d}.md'), 'w', encoding='utf-8').write('\n'.join(out))


def audit(packs):
    """docs/APD-VENDETTA-AUDIT.md: counts, and which lines cannot appear yet because the game does not supply a fact they need."""
    src = open(os.path.join('core', 'src', 'main', 'java', 'com', 'shatteredpixel', 'shatteredpixeldungeon', 'windows', 'GrudgeHooks.java'), encoding='utf-8').read()
    block = src[src.index('SUPPLIED'):]
    block = block[:block.index(') ) );')]
    supplied = set(re.findall(r'"([A-Za-z]+)"', block))
    derived = {'complaintsHeard', 'complaintsTotal', 'appreciationsHeard', 'appreciationsTotal'}
    rows = [f for _, rs in packs for f in rs]
    silent = {}
    for f in rows:
        used = set(re.findall(r'\{([A-Za-z]+)\}', f[5]))
        if f[3] != '-':
            for t in f[3].split('&'):
                m = re.match(r'\s*([A-Za-z]+)', t)
                if m:
                    used.add(m.group(1))
        missing = sorted(k for k in used if k not in supplied and k not in derived)
        if missing:
            silent[f[0]] = missing
    hatred = [f for f in rows if f[1] != 'meta' and not f[0].startswith('app.')]
    appre = [f for f in rows if f[0].startswith('app.')]
    meta = [f for f in rows if f[1] == 'meta']
    with_adult = [f for f in rows if f[6]]
    jokes = [f for f in rows if 'joke' in f[2]]
    out = ['# Cleric grudge: final audit of the library', '', 'Generated by `tools/humor_review.py`.', '',
           f'- Total lines: {len(rows)}', f'- Hatred (counted): {len(hatred)}', f'- Appreciation (counted): {len(appre)}', f'- Counter-screen jokes (not counted): {len(meta)}',
           f'- Lines with their own Adult wording: {len(with_adult)}', f'- Invented-number jokes (labelled fiction): {len(jokes)}',
           f'- Lines that cannot appear yet because a fact is not supplied by the game: {len(silent)}', '',
           f'Facts the game supplies today: {", ".join(sorted(supplied))}.', '', '## Waiting for facts', '', '| id | missing fact(s) |', '|---|---|']
    for k in sorted(silent):
        out.append(f'| {k} | {", ".join(silent[k])} |')
    open(os.path.join('docs', 'APD-VENDETTA-AUDIT.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    return len(rows), len(hatred), len(appre), len(meta), len(silent)


def main():
    packs = read_packs()
    all_ids = [r[0] for _, rows in packs for r in rows]
    counted = [r[0] for _, rows in packs for r in rows if r[1] != 'meta']
    appreciation = [r[0] for _, rows in packs for r in rows if r[1] != 'meta' and r[0].startswith('app.')]
    hatred = [i for i in counted if i not in set(appreciation)]
    previous = set(l.strip() for l in open(IDS, encoding='utf-8') if l.strip() and not l.startswith('#'))
    added = [i for i in all_ids if i not in previous]
    added_h = [i for i in added if not i.startswith('app.') and not i.startswith('meta.')]
    added_a = [i for i in added if i.startswith('app.')]
    adult = sum(1 for _, rows in packs for r in rows if r[6])
    out = ['# Cleric grudge: the lines, for review', '',
           'Generated by `tools/humor_review.py` from `core/src/main/assets/apd/humor/`. Edit the pack files, not this page.', '',
           f'- Lines: {len(all_ids)}: {len(hatred)} Cleric Hatred, {len(appreciation)} Cleric Appreciation, {len(all_ids) - len(counted)} meta (counter jokes)',
           f'- With stronger Adult wording: {adult}',
           f'- Added since the committed id list of the previous release: {len(added_h)} Hatred, {len(added_a)} Appreciation', '',
           'Each line has Clean wording (shown to everyone unless they chose Adult humor) and an optional Adult wording. "When" says what must be true of',
           'recorded facts for the line to be eligible; `{name}` is filled from a recorded value, never invented. Lines marked JOKE use invented numbers on purpose.', '']
    # which content version introduced how many lines, per pool (for truthful patch notes)
    by = {}
    for _, rows in packs:
        for f in rows:
            if f[1] == 'meta':
                continue
            v = next((x[6:] for x in f[2].split(',') if x.strip().startswith('since=')), '?')
            by.setdefault(v, [0, 0])[1 if f[0].startswith('app.') else 0] += 1
    out += ['## By content version', '', '| version | Hatred | Appreciation |', '|---|---|---|']
    for v in sorted(by):
        out.append(f'| {v} | {by[v][0]} | {by[v][1]} |')
    out.append('')
    for name, rows in packs:
        out += [f'## {name}', '', '| id | category | when | Clean | Adult |', '|---|---|---|---|---|']
        for f in rows:
            flags = ' JOKE' if 'joke' in f[2] else ''
            esc = lambda s: s.replace('|', '/').replace('{', '\\{') if s else ''
            out.append(f'| {f[0]}{flags} | {f[1]} | {esc(f[3]) if f[3] != "-" else "any time"} | {esc(f[5])} | {esc(f[6])} |')
        out.append('')
    open(OUT, 'w', encoding='utf-8').write('\n'.join(out))
    write_batches(packs)
    print('audit: %d lines, %d Hatred, %d Appreciation, %d counter, %d waiting for facts' % audit(packs))
    print(f'{len(hatred)} Hatred + {len(appreciation)} Appreciation counted; added since the previous release list: {len(added_h)} Hatred, {len(added_a)} Appreciation; wrote {OUT}')


if __name__ == '__main__':
    sys.exit(main())
